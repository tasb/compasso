#!/usr/bin/env bash
# Generate the pull request workflow from .compasso/project.yaml, for GitHub.
#
#   ci-github.sh --repo R [--scans github|compasso]    writes R/.github/workflows/compasso.yml
#
# Jobs, on pull requests only:
#   compasso-verify          the repo's test, lint, typecheck and build commands   (gate)
#   compasso-e2e             the repo's e2e command, when set                      (gate)
#   compasso-coverage        the coverage command, then diff-cover on changed lines (warning, never fails)
#   compasso-scan-gate       Gitleaks and Semgrep; fails on any secret or high finding (gate; only with --scans compasso)
# Scans: GitHub's own (CodeQL and secret scanning, set up by `github.sh protect`) where the
# repository has them - public, or private with Advanced Security - otherwise Compasso's.
# Without --scans the choice comes from the tracker check.
# Exit: 0 written | 1 config problem
set -u

BIN="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
REPO="." SCANS=""
while [ $# -gt 0 ]; do
  case "$1" in
    --repo) REPO="$2"; shift 2 ;;
    --scans) SCANS="$2"; shift 2 ;;
    *) echo "ci: unknown argument '$1'" >&2; exit 1 ;;
  esac
done
"$BIN/config.sh" validate --repo "$REPO" >/dev/null || exit 1
cfg() { "$BIN/config.sh" get --repo "$REPO" "$1"; }
if [ -z "$SCANS" ]; then
  code="$("$BIN/tracker/github.sh" check --repo "$REPO" | jq -r .capabilities.code_scanning)" || exit 1
  SCANS=compasso; [ "$code" = true ] && SCANS=github
fi
case "$SCANS" in github|compasso) ;; *) echo "ci: --scans is github or compasso" >&2; exit 1 ;; esac

image="$(cfg .ci.image)"
[ -n "$image" ] || { echo "ci: set ci.image in .compasso/project.yaml to the image that has the repo's toolchain" >&2; exit 1; }
yq_str() { v="$1" yq -n 'strenv(v)' ; }   # a YAML-safe scalar for any command string

run_lines=""
for k in test lint typecheck build; do
  c="$(cfg ".commands.$k")"
  [ -n "$c" ] && run_lines="$run_lines      - run: $(yq_str "$c")"$'\n'
done
[ -n "$run_lines" ] || { echo "ci: no test, lint, typecheck or build command in .compasso/project.yaml" >&2; exit 1; }

mkdir -p "$REPO/.github/workflows"
out="$REPO/.github/workflows/compasso.yml"
{
  cat <<EOF
# Generated by Compasso from .compasso/project.yaml; re-run setup to change it.
name: compasso
on:
  pull_request:
permissions:
  contents: read

jobs:
  compasso-verify:
    runs-on: ubuntu-latest
    container: $(yq_str "$image")
    steps:
      - uses: actions/checkout@v4
$run_lines
EOF
  c="$(cfg .commands.e2e)"
  if [ -n "$c" ]; then
    cat <<EOF
  compasso-e2e:
    runs-on: ubuntu-latest
    container: $(yq_str "$image")
    steps:
      - uses: actions/checkout@v4
      - run: $(yq_str "$c")

EOF
  fi
  c="$(cfg .coverage.command)"
  if [ -n "$c" ]; then
    report="$(cfg .coverage.report)"
    cat <<EOF
  compasso-coverage:
    runs-on: ubuntu-latest
    container: $(yq_str "$image")
    steps:
      - uses: actions/checkout@v4
      - run: $(yq_str "$c")
      # the report is read on the runner, not in this container: make its paths relative to the checkout
      - run: sed -i "s#\$GITHUB_WORKSPACE/##g; s#\$GITHUB_WORKSPACE#.#g" $(yq_str "$report")
      - uses: actions/upload-artifact@v4
        with:
          name: compasso-coverage
          path: $(yq_str "$report")

  # Changed-line coverage is a warning: below the threshold it annotates the pull request and passes.
  compasso-coverage-check:
    runs-on: ubuntu-latest
    needs: compasso-coverage
    steps:
      - uses: actions/checkout@v4
        with:
          fetch-depth: 0
      - uses: actions/download-artifact@v4
        with:
          name: compasso-coverage
      - uses: actions/setup-python@v5
        with:
          python-version: "3.12"
      - run: pip install --quiet diff-cover
      - run: |
          diff-cover $(yq_str "$(basename "$report")") --compare-branch="origin/\${{ github.base_ref }}" --fail-under=$(cfg .coverage.min_changed) ||
            echo "::warning title=Changed-line coverage::below $(cfg .coverage.min_changed)% - see the diff-cover output above"

EOF
  fi
  if [ "$SCANS" = compasso ]; then
    cat <<'EOF'
  # GitHub code scanning is not available on this repository: Compasso's scans run instead.
  # Any secret in the pull request's commits, or any high-severity Semgrep finding, blocks the merge.
  compasso-scan-gate:
    runs-on: ubuntu-latest
    steps:
      - uses: actions/checkout@v4
        with:
          fetch-depth: 0
      - name: Secrets (Gitleaks)
        run: |
          docker run --rm -v "$PWD:/repo" zricethezav/gitleaks:latest git /repo \
            --log-opts="${{ github.event.pull_request.base.sha }}..${{ github.event.pull_request.head.sha }}" \
            --report-format json --report-path /repo/gitleaks.json --exit-code 0
          n="$(jq length gitleaks.json)"
          jq -r '.[] | "  - [secret] \(.RuleID) (\(.File):\(.StartLine))"' gitleaks.json
          [ "$n" -eq 0 ] || { echo "scan gate: $n secret(s) in this pull request"; exit 1; }
      - name: Code (Semgrep)
        run: |
          docker run --rm -v "$PWD:/src" -w /src semgrep/semgrep:latest \
            semgrep scan --config p/default --metrics off --json --output /src/semgrep.json /src || true
          [ -f semgrep.json ] || { echo "scan gate: Semgrep did not run"; exit 1; }
          found="$(jq -r '.results[] | select(.extra.severity == "ERROR") | "  - [high] \(.check_id) (\(.path):\(.start.line))"' semgrep.json)"
          [ -z "$found" ] || { echo "scan gate: high findings:"; echo "$found"; exit 1; }
          echo "scan gate: no secrets, no high findings"
EOF
  fi
} > "$out"
yq -e '.' "$out" >/dev/null || { echo "ci: generated $out is not valid YAML" >&2; exit 1; }
echo "ci: wrote $out (scans: $SCANS)"
