#!/usr/bin/env bash
# Generate the merge request pipeline from .compasso/project.yaml.
#
#   ci.sh --repo R        writes R/.gitlab/compasso.gitlab-ci.yml
#
# Jobs, on merge request pipelines only:
#   compasso-verify    the repo's test, lint, typecheck and build commands   (gate)
#   compasso-e2e       the repo's e2e command, when set                      (gate)
#   compasso-coverage  the coverage command, then diff-cover on changed lines (warning: exit 3 allowed)
#   GitLab SAST and Secret Detection                                         (security scans, every tier)
# The product repo includes the file from its .gitlab-ci.yml.
# Exit: 0 written | 1 config problem
set -u

BIN="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
REPO="."
while [ $# -gt 0 ]; do
  case "$1" in
    --repo) REPO="$2"; shift 2 ;;
    *) echo "ci: unknown argument '$1'" >&2; exit 1 ;;
  esac
done
"$BIN/config.sh" validate --repo "$REPO" >/dev/null || exit 1
cfg() { "$BIN/config.sh" get --repo "$REPO" "$1"; }

image="$(cfg .ci.image)"
[ -n "$image" ] || { echo "ci: set ci.image in .compasso/project.yaml to the image that has the repo's toolchain" >&2; exit 1; }
yq_str() { v="$1" yq -n 'strenv(v)' ; }   # a YAML-safe scalar for any command string

script_lines=""
for k in test lint typecheck build; do
  c="$(cfg ".commands.$k")"
  [ -n "$c" ] && script_lines="$script_lines    - $(yq_str "$c")"$'\n'
done
[ -n "$script_lines" ] || { echo "ci: no test, lint, typecheck or build command in .compasso/project.yaml" >&2; exit 1; }

mkdir -p "$REPO/.gitlab"
out="$REPO/.gitlab/compasso.gitlab-ci.yml"
{
  cat <<EOF
# Generated by Compasso from .compasso/project.yaml; re-run setup to change it.
# Include it from .gitlab-ci.yml:  include: [{ local: .gitlab/compasso.gitlab-ci.yml }]
include:
  - template: Jobs/SAST.gitlab-ci.yml
  - template: Jobs/Secret-Detection.gitlab-ci.yml

variables:
  AST_ENABLE_MR_PIPELINES: "true"   # run the security scans in merge request pipelines too

.compasso-mr:
  rules:
    - if: \$CI_PIPELINE_SOURCE == "merge_request_event"

compasso-verify:
  extends: .compasso-mr
  stage: test
  image: $(yq_str "$image")
  script:
$script_lines
EOF
  c="$(cfg .commands.e2e)"
  if [ -n "$c" ]; then
    cat <<EOF
compasso-e2e:
  extends: .compasso-mr
  stage: test
  image: $(yq_str "$image")
  script:
    - $(yq_str "$c")

EOF
  fi
  c="$(cfg .coverage.command)"
  if [ -n "$c" ]; then
    report="$(cfg .coverage.report)"
    visual=""
    case "$report" in *.xml) visual="    reports:
      coverage_report:
        coverage_format: cobertura
        path: $(yq_str "$report")" ;; esac
    cat <<EOF
compasso-coverage:
  extends: .compasso-mr
  stage: test
  image: $(yq_str "$image")
  script:
    - $(yq_str "$c")
  artifacts:
    when: always
    paths:
      - $(yq_str "$report")
$visual

# Changed-line coverage is a warning: below the threshold exits 3, which may fail.
compasso-coverage-check:
  extends: .compasso-mr
  stage: test
  image: python:3.12
  needs: [compasso-coverage]
  allow_failure:
    exit_codes: [3]
  script:
    - pip install --quiet diff-cover
    - git fetch --quiet origin "\$CI_MERGE_REQUEST_TARGET_BRANCH_NAME"
    - diff-cover $(yq_str "$report") --compare-branch="origin/\$CI_MERGE_REQUEST_TARGET_BRANCH_NAME" --fail-under=$(cfg .coverage.min_changed) || exit 3
EOF
  fi
} > "$out"
yq -e '.' "$out" >/dev/null || { echo "ci: generated $out is not valid YAML" >&2; exit 1; }
echo "ci: wrote $out"
