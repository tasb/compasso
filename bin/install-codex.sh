#!/usr/bin/env bash
# Install Compasso for Codex.
#
#   install-codex.sh [--home DIR] [--skills DIR]   once per machine: the engine and the skills
#   install-codex.sh --repo R [--home DIR]         per project: R/.codex/agents/compasso-<role>.toml
#
# Engine: a copy of bin/, roles/, templates/ and skills/ in <home>/engine
#   (default home ${COMPASSO_HOME:-$HOME/.compasso}).
# Skills: <skills>/compasso-<name>/SKILL.md (default ${CODEX_SKILLS_DIR:-$HOME/.agents/skills}),
#   renamed compasso-<name>, with the plugin root rewritten to the engine and
#   /compasso:<x> to $compasso-<x>.
# Agents: one per role, with the model and reasoning effort set for it under
#   models.codex in R/.compasso/project.yaml. Re-run after changing them.
# Everything written carries a marker; files without it are never overwritten,
# and marked files of skills or roles that no longer exist are removed.
# Exit: 0 | 1 refused or failed
set -u

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
HOME_DIR="${COMPASSO_HOME:-$HOME/.compasso}" SKILLS="${CODEX_SKILLS_DIR:-$HOME/.agents/skills}" REPO=""
while [ $# -gt 0 ]; do
  case "$1" in
    --home) HOME_DIR="$2"; shift 2 ;;
    --skills) SKILLS="$2"; shift 2 ;;
    --repo) REPO="$2"; shift 2 ;;
    *) echo "install-codex: unknown argument '$1'" >&2; exit 1 ;;
  esac
done
MARK="generated by compasso install-codex"
ENGINE="$HOME_DIR/engine"
die() { echo "install-codex: $*" >&2; exit 1; }

# the engine path is written into commands the skills run: keep it free of shell syntax
case "$ENGINE" in *[!A-Za-z0-9._/-]*) die "refusing $ENGINE: use a path of letters, digits, '.', '_', '-' and '/' only" ;; esac

install_engine() {
  local s name dest
  if [ -e "$ENGINE" ] && [ ! -f "$ENGINE/.compasso-engine" ]; then die "$ENGINE exists and is not a Compasso engine; left untouched"; fi
  for s in "$ROOT"/skills/*/SKILL.md; do          # refuse before writing anything
    dest="$SKILLS/compasso-$(basename "$(dirname "$s")")/SKILL.md"
    if [ -f "$dest" ] && ! grep -qF "$MARK" "$dest"; then die "$dest is not Compasso's; left untouched"; fi
  done
  rm -rf "$ENGINE" && mkdir -p "$ENGINE" || die "cannot write $ENGINE"
  cp -R "$ROOT/bin" "$ROOT/roles" "$ROOT/templates" "$ROOT/skills" "$ENGINE/" || die "cannot copy the engine"
  echo "$MARK" > "$ENGINE/.compasso-engine"

  mkdir -p "$SKILLS" || die "cannot write $SKILLS"
  for s in "$SKILLS"/compasso-*/SKILL.md; do          # skills that no longer exist
    [ -f "$s" ] || continue
    name="$(basename "$(dirname "$s")")"; name="${name#compasso-}"
    grep -qF "$MARK" "$s" && [ ! -f "$ROOT/skills/$name/SKILL.md" ] && rm -rf "$(dirname "$s")"
  done
  for s in "$ROOT"/skills/*/SKILL.md; do
    name="$(basename "$(dirname "$s")")"
    dest="$SKILLS/compasso-$name/SKILL.md"
    mkdir -p "$(dirname "$dest")"
    awk -v name="compasso-$name" -v engine="$ENGINE" -v mark="$MARK" '
      NR == 1 && $0 == "---" { fm = 1; print; next }
      fm && /^name:/ { print "name: " name; next }
      fm && $0 == "---" { fm = 0; print
        print "<!-- " mark " -->"
        print ""
        print "On Codex, each Compasso role runs as the custom agent `compasso-<role>` from this project\x27s `.codex/agents/` (written by `" engine "/bin/install-codex.sh --repo .`), which already carries its model and reasoning effort."
        next }
      { line = $0
        gsub(/\$\{CLAUDE_PLUGIN_ROOT\}/, engine, line)
        while (match(line, /\/compasso:[a-z-]+/)) line = substr(line, 1, RSTART - 1) "$compasso-" substr(line, RSTART + 10, RLENGTH - 10) substr(line, RSTART + RLENGTH)
        print line }' "$s" > "$dest" || die "cannot write $dest"
  done
  echo "install-codex: engine in $ENGINE; $(ls -d "$SKILLS"/compasso-*/ | wc -l | tr -d ' ') skills in $SKILLS"
}

install_agents() {
  local cfg="$REPO/.compasso/project.yaml" dir="$REPO/.codex/agents" r role dest body model effort desc
  "$ENGINE/bin/config.sh" validate --repo "$REPO" >/dev/null 2>&1 || {
    [ -x "$ENGINE/bin/config.sh" ] || die "no engine in $ENGINE: run install-codex.sh first"
    die "$cfg is not valid: run $ENGINE/bin/config.sh validate --repo $REPO"; }
  yq -e '.harnesses[] | select(. == "codex")' "$cfg" >/dev/null 2>&1 || die "codex is not in harnesses in $cfg"
  mkdir -p "$dir" || die "cannot write $dir"
  for r in "$dir"/compasso-*.toml; do                 # roles that no longer exist
    [ -f "$r" ] || continue
    role="$(basename "$r" .toml)"; role="${role#compasso-}"
    grep -qF "$MARK" "$r" && [ ! -f "$ENGINE/roles/$role.md" ] && rm -f "$r"
  done
  for r in "$ENGINE"/roles/*.md; do
    role="$(basename "$r" .md)"
    dest="$dir/compasso-$role.toml"
    if [ -f "$dest" ] && ! grep -qF "$MARK" "$dest"; then die "$dest is not Compasso's; left untouched"; fi
    desc="$(yq --front-matter=extract -r '.description // ""' "$r" 2>/dev/null)"
    [ -n "$desc" ] || die "$r has no readable description in its frontmatter"
    body="$(awk 'BEGIN{n=0} /^---[[:space:]]*$/{n++; next} n>=2' "$r")"
    case "$body" in *"'''"*) die "$r contains ''' and cannot be a TOML literal string" ;; esac
    model="$(R="$role" yq -r '.models.codex[strenv(R)].model // ""' "$cfg")"
    effort="$(R="$role" yq -r '.models.codex[strenv(R)].effort // ""' "$cfg")"
    {
      echo "# $MARK --repo; re-run it after changing models.codex in .compasso/project.yaml"
      echo "name = $(jq -rn --arg v "compasso-$role" '$v | @json')"
      echo "description = $(jq -rn --arg v "$desc" '$v | @json')"
      [ -n "$model" ] && echo "model = $(jq -rn --arg v "$model" '$v | @json')"
      [ -n "$effort" ] && echo "model_reasoning_effort = $(jq -rn --arg v "$effort" '$v | @json')"
      echo "developer_instructions = '''"
      printf '%s\n\n' "$body"
      echo "Your inputs are the file paths you are given, relative to the repository; read them. Compasso's scripts are in $ENGINE/bin."
      echo "'''"
    } > "$dest" || die "cannot write $dest"
  done
  echo "install-codex: $(ls "$dir"/compasso-*.toml | wc -l | tr -d ' ') agents in $dir"
}

if [ -n "$REPO" ]; then install_agents; else install_engine; fi
