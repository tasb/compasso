#!/usr/bin/env bash
# Generate the Claude Code subagents in agents/ from roles/, the single source.
#
#   gen-agents.sh           write agents/<role>.md for every dispatched role
#   gen-agents.sh --check   exit 1, listing them, when agents/ differs from what roles/ generates
#
# Each agent (invoked as compasso:<role>) carries its role's description and text, the
# tools the role lists (never Agent: a subagent cannot start another), maxTurns from the
# role's max_turns, and the Claude model from templates/project.yaml as a default: the
# orchestrator passes the project's own model at dispatch, which takes precedence.
# Roles with `dispatch: inline` (the planner) run in the conversation and get no agent.
# Exit: 0 | 1 out of date (--check) or a malformed role | 2 usage
set -u

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
CHECK=0
case "${1:-}" in --check) CHECK=1 ;; "") ;; *) echo "gen-agents: unknown argument '$1'" >&2; exit 2 ;; esac

OUT="$ROOT/agents"; [ "$CHECK" -eq 1 ] && OUT="$(mktemp -d)"
mkdir -p "$OUT"
for f in "$ROOT"/roles/*.md; do
  role="$(basename "$f" .md)"
  fm="$(yq --front-matter=extract -o=json . "$f")" || { echo "gen-agents: $f has no readable frontmatter" >&2; exit 1; }
  [ "$(jq -r '.dispatch // ""' <<<"$fm")" = inline ] && continue
  tools="$(jq -r '.tools // ""' <<<"$fm")" turns="$(jq -r '.max_turns // ""' <<<"$fm")"
  [ -n "$tools" ] && [ -n "$turns" ] || { echo "gen-agents: $f needs tools and max_turns" >&2; exit 1; }
  case ",$(printf '%s' "$tools" | tr -d ' ')," in *,Agent,*|*,Task,*) echo "gen-agents: $role may not have the Agent tool: only the orchestrator dispatches" >&2; exit 1 ;; esac
  model="$(yq -r ".models.claude.$role.model // \"inherit\"" "$ROOT/templates/project.yaml")"
  {
    printf -- '---\nname: %s\ndescription: %s\ntools: %s\nmodel: %s\nmaxTurns: %s\n---\n\n' \
      "$role" "$(jq -r '.description | @json' <<<"$fm")" "$tools" "$model" "$turns"
    echo "<!-- Generated by bin/gen-agents.sh from roles/$role.md: edit the role, then run bin/gen-agents.sh. -->"
    awk 'BEGIN{n=0} /^---[[:space:]]*$/ && n<2 {n++; next} n>=2' "$f"
  } > "$OUT/$role.md"
done

if [ "$CHECK" -eq 1 ]; then
  stale="$(diff -rq "$OUT" "$ROOT/agents" 2>&1 | sed "s#$OUT#generated#g; s#$ROOT/##g")"
  rm -rf "$OUT"
  [ -z "$stale" ] || { echo "gen-agents: agents/ is out of date - run bin/gen-agents.sh:"; printf '%s\n' "$stale" | sed 's/^/  /'; exit 1; }
  echo "gen-agents: agents/ matches roles/"
else
  echo "gen-agents: wrote $(ls "$OUT" | wc -l | tr -d ' ') agents to agents/"
fi
